    private void iniciarCombos() {
        this.cmbTipo.removeAllItems();

        this.cmbTipo.addItem("Computadora");
        this.cmbTipo.addItem("Impresora");
        this.cmbTipo.addItem("Monitor");
        this.cmbTipo.addItem("Laptop");
    }

    private void leerTienda() {
        try (FileInputStream fis = new FileInputStream("tienda.txt"); ObjectInputStream ois = new ObjectInputStream(fis)) {
            tienda = (Tienda) ois.readObject();
            ArrayList<Equipo> lis = tienda.getListado();
            for (Equipo e : lis) {
                System.out.println(e.toString());
            }
        } catch (IOException e) {
            System.out.println(e.getMessage());
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        }
    }

    private void llenarTabla(ArrayList<Equipo> listado) {

        DefaultTableModel dtm = (DefaultTableModel) tblEquipos.getModel();
        dtm.setNumRows(0);
        for (Equipo e : listado) {
            dtm.addRow(new Object[]{
                e.getNombre(),
                e.getMarca(),
                e.getTipo(),
                e.getProcesador(),
                e.getPrecio()
            });
        }
    }

    private void iniciarTabla() {

        String[] columnNames = {"Nombre", "Marca", "Tipo", "Procesador","Precio"};

        Object[][] data = new Object[][]{};

        DefaultTableModel dtm = new DefaultTableModel(data, columnNames) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblEquipos.setModel(dtm);
    }

