    private void guardarTienda(Tienda tienda) {
        try {
            FileOutputStream fos = new FileOutputStream("tienda.txt");
            ObjectOutputStream oos = new ObjectOutputStream(fos);
            oos.writeObject(tienda);
            oos.close();
            fos.close();
        } catch (IOException e) {
            System.out.println(e.getMessage());
        }
    }
    
