    private void btnAdicionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdicionarActionPerformed
        // TODO add your handling code here:
        String nombre, marca, tipo, procesador, mensaje;
        float precio;

        nombre = this.txtNombre.getText();
        marca = this.cmbMarca.getSelectedItem().toString();
        tipo = this.cmbTipo.getSelectedItem().toString();
        precio = Float.parseFloat(this.spiPrecio.getValue().toString());
        procesador = this.cmbProcesador.getSelectedItem().toString();
        

        if (!nombre.equals("") && !marca.equals("") && !tipo.equals("")) {
            Equipo equipo = new Equipo(nombre, marca, tipo, precio, procesador);
            tienda.addEquipo(equipo);
            llenarTabla();

            txtNombre.setText("");
            cmbMarca.setSelectedIndex(0);
            cmbTipo.setSelectedIndex(0);
            spiPrecio.setValue(1);

        } else {
            mensaje = "Todos los datos son obligatorios";
            JOptionPane.showMessageDialog(this, mensaje,
                    "Ingreso de Animales",
                    JOptionPane.WARNING_MESSAGE);
        }

    }//GEN-LAST:event_btnAdicionarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        DefaultTableModel dtm = (DefaultTableModel) tblEquipos.getModel();
        int numFilas = dtm.getRowCount();
        int filaSel;
        if(numFilas > 0) {
            filaSel = tblEquipos.getSelectedRow();
            if(filaSel != -1) {
                int dialogResult = JOptionPane.showConfirmDialog(null, "Confirmar el borrado del equipo?", "Advertencia", JOptionPane.YES_OPTION);
                if(dialogResult == JOptionPane.YES_OPTION) {
                    tienda.eliminarEquipo(filaSel);
                    llenarTabla();
                    
                    JOptionPane.showMessageDialog(this, "Equipo eliminado", "Eliminar equipo",JOptionPane.INFORMATION_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Seleccione un equipo a eliminar", "Eliminar equipo",JOptionPane.WARNING_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, "No hay equipo para eliminar", "Eliminar equipo",JOptionPane.WARNING_MESSAGE);
        }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

