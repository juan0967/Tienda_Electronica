    private Tienda leerTienda() {
        try {
            FileInputStream fis = new FileInputStream("tienda.txt");
            ObjectInputStream ois = new ObjectInputStream(fis);
            tienda = (Tienda) ois.readObject();
            System.out.println(tienda.getDireccion());
            ArrayList<Equipo> lis = tienda.getListado();
            for (Equipo a : lis) {
                System.out.println(a.toString());
            }
        } catch (IOException e) {
            this.tienda = new Tienda("Tienda", "123456789", "Guayaquil");
            guardarTienda(this.tienda);
            System.out.println(e.getMessage());
        } catch (ClassNotFoundException e) {
            System.out.println(e.getMessage());
        } finally {
            return tienda;
        }
    }

    private void llenarTabla() {
        ArrayList<Equipo> listado = tienda.getListado();

        DefaultTableModel dtm = (DefaultTableModel) tblEquipos.getModel();
        dtm.setNumRows(0);
        for (Equipo e : listado) {
            dtm.addRow(new Object[]{e.getNombre(),
                e.getMarca(),
                e.getTipo(),
                e.getProcesador(),
                e.getPrecio()
            });
        }
    }

    private void iniciarTabla() {
        String[] columnNames = {
            "Nombre", "Marca", "Tipo","Procesador", "Precio"
        };
        Object[][] data = new Object[][]{};

        DefaultTableModel dtm = new DefaultTableModel(data, columnNames) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblEquipos.setModel(dtm);
    }

